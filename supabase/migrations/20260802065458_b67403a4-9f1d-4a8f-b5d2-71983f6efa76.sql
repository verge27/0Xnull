## CS2 Match Structure (What You're Betting On)

Professional CS2 matches are typically best-of-one (BO1) in group stages and best-of-three (BO3) in playoffs. Each map is 30 rounds (first to 16 wins), with a potential overtime at 15-15.

### CS2 bet types explained

- **Match winner**: Who wins the overall match
- **Map winner**: Who wins a specific map
- **Total maps**: Over/under on number of maps played
- **Handicap**: One team starts with +1.5 or -1.5 map advantage
- **Round handicap**: Margin betting inside a single map
- **Pistol round winner**: A short-market bet on the opening round of a half
- **Tournament winner**: Outright winner of a tournament

### Reading CS2 betting odds

Decimal odds of 2.00 imply a 50% win chance. Convert odds to an implied probability (1 ÷ decimal odds), then compare it to your own estimate. A bet only has value when your estimate is higher than the implied probability.

## Key Factors in CS2 Betting

### Map pool

Teams have varying strengths across the seven active maps. Before betting, check each team's win rate and rating on specific maps using HLTV stats. A top team's "best map" vs the opponent's "worst map" can swing the odds significantly.

### Roster changes

CS2 teams frequently change rosters. A new player joining can disrupt team dynamics even if individually skilled. Check announcement dates — teams in the first 2-4 weeks with a new player often underperform expectations.

### Recent form

Check the last 3 months of results. HLTV rating, head-to-head record, and recent tournament performance all matter. Teams entering Major qualification cycles often peak; teams post-Major sometimes dip.

### Online vs LAN

Some rosters are far stronger online than on LAN. Crowd pressure, stage nerves, and travel fatigue all show up in LAN results, so weight LAN data more heavily for Tier 1 events.

### Odds value

The best bets are when the market misprices a team. If you think a team has a 55% win chance but the market shows 45% (implied odds of ~2.22), that's a value bet.

