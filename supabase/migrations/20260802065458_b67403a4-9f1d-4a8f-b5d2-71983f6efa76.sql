## Setting Up Securely

After provisioning the VPS: disable password login (use SSH keys only), configure a firewall (ufw or iptables), keep the OS updated automatically, and consider full disk encryption if the provider supports it.

### A minimal hardening checklist

- Create a non-root user and disable direct root SSH
- Move SSH off port 22 and rate-limit connection attempts
- Install unattended upgrades for security patches
- Enable fail2ban or an equivalent ban list
- Take encrypted off-server backups you control

